// Lightweight i18n (decision 14): the English string IS the key, the
// dictionary maps EN -> IT, a missing key falls back to English. The app can
// never show a broken key; at worst it shows English. gettext style: no file
// of symbolic keys to keep in sync.
//
// Interpolation with `{name}` placeholders: the key contains them literally,
// `t()` substitutes them AFTER the lookup, so a translation can reorder them.
// Numbers go through `locale()` for formatting.
//
// The language is a setting (§16): `t()` reads it on every call, so a
// change applies at once — the Studio root re-renders on the settings
// `version`, the editor reconfigures its search phrases.

import { setting, useSettings } from "./settings";
import { SettingValues } from "./settingsSchema";

export type Lang = SettingValues["appearance.language"];

export function lang(): Lang {
  return setting("appearance.language");
}

/// The settings `version`, for a memoized component that shows translated
/// text: subscribing makes it re-render on a language change.
export function useLang(): number {
  return useSettings((s) => s.version);
}

/// Locale for `toLocaleString` on numbers, consistent with the UI language.
export function locale(): string {
  return lang() === "en" ? "en-US" : "it";
}

export function t(s: string, params?: Record<string, string | number>): string {
  let out = lang() === "it" ? (IT[s] ?? s) : s;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

/// The text in both languages, lowercased, for a search that must find a
/// setting by its Italian or its English name whatever the UI language.
export function searchText(s: string): string {
  return `${s} ${IT[s] ?? ""}`.toLowerCase();
}

/// Italian strings of an extension build (architecture §13), registered
/// before the app renders.
export function addTranslations(extra: Record<string, string>): void {
  Object.assign(IT, extra);
}

/// Translates a message produced by the backend (Rust), which writes it in
/// English. Exact match first (both dictionaries), then the `MSG` keys with
/// placeholders as patterns: `root CA {path}: {e}` matches
/// `root CA /x.pem: bad file` and the captured values are put back into the
/// Italian text, translated in turn (a backend message often wraps another
/// one). Anything unknown (server errors from PostgreSQL/MySQL, OS errors)
/// comes back unchanged.
export function tMsg(s: string | null | undefined): string {
  if (s == null) return "";
  return lang() === "it" ? translateMsg(s, 0) : s;
}

type MsgPattern = { re: RegExp; slots: string[]; it: string; fixed: number };

let patterns: MsgPattern[] | null = null;

const PLACEHOLDER = /\{[^{}]*\}/g;

function msgPatterns(): MsgPattern[] {
  if (patterns) return patterns;
  patterns = [];
  for (const [en, it] of Object.entries(MSG)) {
    const slots = en.match(PLACEHOLDER);
    if (!slots) continue;
    const literal = en.split(PLACEHOLDER).map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
    const fixed = literal.join("").length;
    patterns.push({ re: new RegExp("^" + literal.join("([\\s\\S]+?)") + "$"), slots, it, fixed });
  }
  // Most specific first: `root CA {}: no certificate in the file` must win
  // over `root CA {}: {e}`.
  patterns.sort((x, y) => y.fixed - x.fixed);
  return patterns;
}

function translateMsg(s: string, depth: number): string {
  const exact = MSG[s] ?? IT[s];
  if (exact !== undefined) return exact;
  if (depth > 2) return s;
  for (const p of msgPatterns()) {
    const m = p.re.exec(s);
    if (!m) continue;
    // Placeholders are matched by their text, in order: `{}` twice in the
    // English key fills the first and then the second `{}` of the Italian.
    const used = new Array(p.slots.length).fill(false);
    return p.it.replace(PLACEHOLDER, (tok) => {
      const i = p.slots.findIndex((slot, k) => !used[k] && slot === tok);
      if (i < 0) return tok;
      used[i] = true;
      return translateMsg(m[i + 1], depth + 1);
    });
  }
  return s;
}

